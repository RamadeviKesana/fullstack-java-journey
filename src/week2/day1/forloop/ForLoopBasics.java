package week2.day1.forloop;

public class ForLoopBasics {

    public static void main(String[] args) {

        System.out.println("Ascending:");

        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

        System.out.println("Descending:");

        for (int i = 10; i >= 1; i--) {
            System.out.println(i);
        }
    }
}